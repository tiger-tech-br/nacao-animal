"use strict";

/* ==================================================
   ALERTA
================================================== */

function showAlert(message) {

    alert(message);

}

/* ==================================================
   SUCESSO
================================================== */

function showSuccess(message) {

    alert(`✅ ${message}`);

}

/* ==================================================
   ERRO
================================================== */

function showError(message) {

    alert(`❌ ${message}`);

}

/* ==================================================
   AVISO
================================================== */

function showWarning(message) {

    alert(`⚠️ ${message}`);

}

/* ==================================================
   CONFIRMAÇÃO
================================================== */

function showConfirm(message) {

    return confirm(message);

}